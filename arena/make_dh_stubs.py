#!/usr/bin/env python3
"""arena/make_dh_stubs.py — build the three `dh` signature variants rmc_ts.py must survive.

`rmc_ts.py` filters its kwargs against whatever `TSStripper.__init__` the
installed `dh` declares, so that old and new revisions of your module both work.
That claim is only worth something if it is exercised, so this script emits three
importable packages, each named `dh`:

    current/   the plain stub                  (all nine kwargs accepted)
    old/       a 4-kwarg signature             (no preserve_*/validate)
    kwargs/    __init__(**kwargs)              (signature unreadable -> pass everything)

Each variant directory contains `dh.py` (and, for the wrappers, `_dh_base.py`)
and is used as a PYTHONPATH entry:

    python arena/make_dh_stubs.py -o /tmp/dhstubs
    PYTHONPATH=/tmp/dhstubs/old .venv/bin/python rmc_ts.py src/ -n

Exit codes: 0 written · 1 the stub could not be imported (missing tree-sitter) · 2 bad usage
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

WRAPPER_HEADER = '''"""dh variant generated by arena/make_dh_stubs.py — TEST HARNESS ONLY.

{what}
"""

from _dh_base import SKIP_DIRS, TSStripper as _Base, atomic_write  # noqa: F401


class TSStripper(_Base):
{signature}
'''

OLD_SIGNATURE = '''    def __init__(self, strip_comments=True, strip_docstrings=True,
                 preserve_shebangs=True, preserve_module_docstring=True,
                 preserve_directives=True, validate=True):
        # the signature set rmc_termux.py actually configures: no
        # remove_blank_lines (it collapses blank lines itself, afterwards) and no
        # preserve_commented_code.  rmc_ts.py must notice that from the signature,
        # not pass those two, and still honour --remove-blank-lines on its own.
        super().__init__(
            strip_comments=strip_comments,
            strip_docstrings=strip_docstrings,
            preserve_shebangs=preserve_shebangs,
            preserve_module_docstring=preserve_module_docstring,
            preserve_directives=preserve_directives,
            validate=validate,
        )
'''

KWARGS_SIGNATURE = '''    def __init__(self, **kwargs):
        # a newer dh that absorbs anything; rmc_ts.py must pass everything through
        super().__init__(**kwargs)
'''


def build(out: Path, base: Path) -> list[Path]:
    variants: dict[str, str | None] = {
        "current": None,
        "old": WRAPPER_HEADER.format(
            what="Older dh.TSStripper: four kwargs, none of the preserve_* knobs.",
            signature=OLD_SIGNATURE,
        ),
        "kwargs": WRAPPER_HEADER.format(
            what="Newer dh.TSStripper: __init__(**kwargs).",
            signature=KWARGS_SIGNATURE,
        ),
    }
    written: list[Path] = []
    for name, wrapper in variants.items():
        directory = out / name
        directory.mkdir(parents=True, exist_ok=True)
        if wrapper is None:
            shutil.copy2(base, directory / "dh.py")
        else:
            shutil.copy2(base, directory / "_dh_base.py")
            (directory / "dh.py").write_text(wrapper, encoding="utf-8")
        written.append(directory / "dh.py")
    return written


def probe(paths: list[Path], python: str) -> bool:
    """Each variant must import and strip one comment, or the file is a lie."""
    ok = True
    for path in paths:
        code = (
            "import dh;"
            "print(repr(dh.TSStripper().strip('def f():\\n    \"\"\"d\"\"\"\\n    return 1  # c\\n')))"
        )
        result = subprocess.run(
            [python, "-c", code],
            cwd=path.parent.parent,
            env={"PYTHONPATH": str(path.parent), "PATH": "/usr/bin:/bin"},
            capture_output=True,
            text=True,
        )
        label = path.parent.name
        if result.returncode == 0:
            print(f"  {label:8} ok   {result.stdout.strip()}")
        else:
            ok = False
            print(f"  {label:8} FAIL {result.stderr.strip().splitlines()[-1:]}")
    return ok


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("-o", "--out", type=Path, default=Path("/tmp/dhstubs"),
                        help="output directory (default: /tmp/dhstubs)")
    parser.add_argument("--base", type=Path, default=HERE / "dh_stub.py",
                        help="the plain stub to derive from (default: arena/dh_stub.py)")
    parser.add_argument("--python", default=sys.executable, help="interpreter used for the import probe")
    args = parser.parse_args(argv)

    if not args.base.is_file():
        print(f"base stub not found: {args.base}", file=sys.stderr)
        return 2

    args.out.mkdir(parents=True, exist_ok=True)
    paths = build(args.out, args.base)
    print(f"wrote {len(paths)} dh variants under {args.out}:")
    for path in paths:
        print(f"  {path}")
    print("probing each one:")
    if not probe(paths, args.python):
        print("at least one variant failed to import — is tree_sitter installed?", file=sys.stderr)
        return 1
    print("\nuse one with:\n  PYTHONPATH=$PWD/arena ... " f"-- actually: PYTHONPATH={args.out}/old ...")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
